/* Options are edited in the SHIFT+MENU menu and persisted to one small file,
 * which also remembers the folder the browser was left in. The format is one
 * "key=value" line per entry, so adding options stays backwards compatible.
 * The file is itself a dotfile, hidden from the listing unless "Show hidden
 * files" is on. */
#define CFG_PATH "/TEXTEDIT/.textedit.cfg"

static int g_rememberDir = 0;   /* reopen the last folder on the next launch */

/* SI_CHOICE is a value picked from a short named list (see `names`), cycled
 * rather than incremented; it still stores a plain int, so the config file
 * needs nothing new. */
enum { SI_BOOL, SI_INT, SI_CHOICE };

/* Labels for the character-set choice, indexed by the stored value. */
static const char *const g_charsetNames[] = {
    "Prizm standard", "Windows (ANSI)", "DOS/IBM-ASCII (OEM)"
};
#define CHARSET_N ((int)(sizeof(g_charsetNames) / sizeof(g_charsetNames[0])))

/* Syntax-highlighting mode for the text editor. The tokenizer itself lives
 * further down, just above editor_session(); 0 = plain text, no colouring. */
static int g_syntax = 0;
static const char *const g_syntaxNames[] = { "Plain text", "Python", "C++", "Java" };
#define SYNTAX_N ((int)(sizeof(g_syntaxNames) / sizeof(g_syntaxNames[0])))

/* Which face the add-in draws with. Every bundled face is a fixed-advance
 * cell, because the editor and the hex view address a text column n as
 * x = n * width. The proportional faces (Noto Sans, Source Sans 3, Comic Sans,
 * Roboto) are rasterized into one cell width for exactly that reason, so they
 * read as a monospaced cut of themselves and the grid still holds.
 *
 * Mode 0 is the odd one out: gint's own proportional 8x9 is ASCII-only and has
 * no fixed width, so it can drive the chrome but the editing surfaces must
 * fall back to the code-page face. That is the "coexistence" this option
 * provides; every other mode is one face for both. */
static int g_fontMode = 1;      /* index into g_fontNames / g_faces */
static const char *const g_fontNames[] = {
    "Default", "Code page", "Lucida Console", "Consolas",
    "Noto Sans", "Source Sans 3", "Comic Sans MS", "Roboto"
};
#define FONT_N ((int)(sizeof(g_fontNames) / sizeof(g_fontNames[0])))

/* One row per name above, same order. get == NULL means gint's built-in
 * default; w is the cell width the editing surfaces must grid by. */
struct Face {
    font_t const *(*get)(void);
    int w;
};
static const struct Face g_faces[] = {
    { NULL,         WC_W  },
    { wc_font_get,  WC_W  },
    { luc_font_get, LUC_W },
    { con_font_get, CON_W },
    { not_font_get, NOT_W },
    { ss3_font_get, SS3_W },
    { cms_font_get, CMS_W },
    { rob_font_get, ROB_W },
};

/* A face must exist behind every name: fail the build rather than let the menu
 * list something with no glyph data behind it. */
typedef char font_names_and_faces_must_match[
    ((int)(sizeof(g_faces) / sizeof(g_faces[0])) == FONT_N) ? 1 : -1];

/* key  : name used in the config file (no spaces)
 * name : label shown in the menu
 * value: pointer to the live option
 * red  : draw this row on a red bar (used to set the hex switch apart)
 * names/nNames: SI_CHOICE label list and its length, names[value] shown right
 * SI_INT uses lo/hi/step; SI_BOOL ignores everything but key/name/value. */
struct Setting {
    const char *key;
    const char *name;
    int *value;
    int kind;
    int lo, hi, step;
    int red;
    const char *const *names;
    int nNames;
};

