/* --------------------------- text character set --------------------------
 * A raw byte in a text file means whatever the file's code page says it does.
 * We let the user pick the page in the SHIFT+MENU list and turn each byte into
 * the matching Unicode code point:
 *
 *   0 = Standard        ISO-8859-1 (Latin-1): byte == code point
 *   1 = Windows (ANSI)  Windows-1252, via wc_cp1252[]
 *   2 = DOS/IBM (OEM)   CP437, via wc_cp437[]
 *
 * gint decodes UTF-8 before it looks a glyph up, so the code point is then
 * re-encoded as UTF-8 into the draw buffer. The bundled font (wcfont.c) has a
 * real glyph for every code point either page can produce, which is why the
 * old "one ASCII stand-in per byte" hack is gone: matches, box drawing,
 * shaded blocks, arrows, card suits and Greek letters now all draw properly.
 *
 * The mapping is strictly one byte -> one glyph, so the byte column the caret
 * and the selection live on is still display character n of the line. */
static int g_charset = 0;       /* see the list in g_charsetNames[] */

/* Longest run of one line that is ever encoded for display. A screen row
 * holds ~49 characters, so this is far more than can be seen; it only bounds
 * the draw buffers. */
#define DISP_MAX 200

/* Draw buffer for one line plus the UTF-8 byte offset of every character in
 * it (so a caret or a selection span can index the buffer by column).
 * Static on purpose: the add-in is single-threaded and this keeps ~1.8 KB
 * off the stack. */
static char g_disp[DISP_MAX * 3 + 1];
static int  g_dispOff[DISP_MAX + 1];

/* Code point for one raw byte under the active character set. The DOS page
 * gives its control slots real graphics (smileys, suits, arrows), so those
 * resolve through wc_cp437_lo[]; the ANSI and Latin-1 pages have nothing there
 * and fall back to a dot, which keeps the column layout identical either way.
 * DEL is U+2302 on the DOS page and a dot everywhere else. */
static uint16_t enc_cp(unsigned char b) {
    if(b < 0x20) {
        if(g_charset == 2) { uint16_t cp = wc_cp437_lo[b]; if(cp) return cp; }
        return '.';
    }
    if(b == 0x7f) return (g_charset == 2) ? 0x2302 : '.';
    if(b < 0x80) return b;                       /* ASCII is shared by all */
    if(g_charset == 1) return wc_cp1252[b - 0x80];
    if(g_charset == 2) return wc_cp437[b - 0x80];
    return b;                                    /* Standard: Latin-1 */
}

/* Write one code point as UTF-8; returns the byte count (1..3: nothing a
 * byte-oriented character set can name lives above the BMP). */
static int utf8_put(char *dst, uint16_t cp) {
    if(cp < 0x80) { dst[0] = (char)cp; return 1; }
    if(cp < 0x800) {
        dst[0] = (char)(0xC0 |  (cp >> 6));
        dst[1] = (char)(0x80 |  (cp & 0x3F));
        return 2;
    }
    dst[0] = (char)(0xE0 |  (cp >> 12));
    dst[1] = (char)(0x80 | ((cp >> 6) & 0x3F));
    dst[2] = (char)(0x80 |  (cp & 0x3F));
    return 3;
}

/* Encode a source byte slice [src, src+n) for the active character set into
 * dst as UTF-8, one glyph per byte: `off[c]` records where byte c starts in
 * dst and may be NULL. Returns the byte count, which is also the number of
 * columns the slice occupies -- the byte column the caret and the selection
 * live on is display character n of the line. */
static int enc_line(char *dst, int *off, const char *src, int n) {
    int p = 0;
    for(int i = 0; i < n; i++) {
        if(off) off[i] = p;
        p += utf8_put(dst + p, enc_cp((unsigned char)src[i]));
    }
    if(off) off[n] = p;
    dst[p] = 0;
    return n;
}

